"""Переводы: русский, английский, финский.

t("ключ", **числа) — строка на текущем языке. Нет перевода — берётся русская.
Числа подставляются через {имя}, например t("popup.ammo", n=20).
"""
import sys

LANGS = {"ru": "Русский", "en": "English", "fi": "Suomi"}
DEFAULT_LANG = "ru"
_lang = DEFAULT_LANG


def guess_lang():
    """Язык системы, если он есть в игре (ru_RU.UTF-8 -> ru; на Windows — Russian_Russia), иначе английский.
    Только чтобы подсветить строку на экране выбора языка при первом запуске."""
    import locale
    import os
    names = {"russian": "ru", "finnish": "fi", "english": "en"}
    cands = [os.environ.get(k, "") for k in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE")]
    if sys.platform == "emscripten":                  # браузер: язык из его настроек
        try:
            import platform as js
            cands.insert(0, str(js.window.navigator.language or ""))
        except Exception:
            pass
    try:
        cands.append(locale.getlocale()[0] or "")
    except (ValueError, TypeError):
        pass
    for c in cands:
        c = c.lower()
        for code in LANGS:
            if c[:2] == code:
                return code
        for name, code in names.items():
            if c.startswith(name):
                return code
    return "en"


def set_lang(code):
    global _lang
    _lang = code if code in LANGS else DEFAULT_LANG


def get_lang():
    return _lang


def t(key, **kw):
    text = TEXTS[_lang].get(key) or TEXTS[DEFAULT_LANG][key]
    return text.format(**kw) if kw else text


