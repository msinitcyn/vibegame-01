"""Команда игрока на один такт матча — всё, что матч знает о вводе.

Клавиатура, геймпад (а потом и сеть) превращаются в команды в приложении;
сами правила о клавишах ничего не знают.
"""
from dataclasses import dataclass


@dataclass
class Command:
    move: tuple = (0, 0)          # (dx, dy): каждое -1, 0 или 1 — куда маг идёт в этот такт
    fire: bool = False            # нажат выстрел (с прошлого такта)
    melee: bool = False           # нажат ближний удар
    use_slot: int = None          # нажата ячейка инвентаря 0–3 (или None)
    aim: float = None             # прицел, радианы (0 — вправо, π — влево, ось Y вниз); None — не менять
    reach: float = None           # до курсора, пикс (огненный круг встаёт там); REACH_FAR — курсора нет; None — не менять


REACH_FAR = 1e6                   # «курсора нет» (стик, клавиши, бот): заклинания «в точку» — на всю дальность
