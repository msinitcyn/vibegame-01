def resource_root():
    """Где лежат файлы игры: папка проекта или, внутри готовой сборки, папка распаковки."""
    unpacked = getattr(sys, "_MEIPASS", None)
    return Path(unpacked) if unpacked else Path(__file__).resolve().parent.parent


